const {test, expect} = require('/opt/node_modules/@playwright/test');
const crypto = require('crypto');
const payload = Buffer.from('synthetic launcher fixture');
const sha = crypto.createHash('sha256').update(payload).digest('hex');
test('launcher copies with progress, persists sidecar, detects stale Pack and starts game', async ({page}) => {
  const failures = [];
  page.on('pageerror', e => failures.push(String(e)));
  await page.route('**/version.txt', r => r.fulfill({body:'0123456789abcdef'}));
  await page.route('**/__fixture/us.pack.sha256', r => r.fulfill({body:sha + '\n'}));
  // Worker fetches are served by the local fixture server, not page routing.
  await page.goto('/');
  await expect(page.locator('#version')).toHaveText('0123456789abcdef');
  await expect(page.locator('#pack-status')).toHaveText('Pack ausente');
  await expect(page.locator('#play')).toBeDisabled();
  // Redirect the worker request to the synthetic Pack generated by run.py io.
  await page.evaluate(() => {
    const NativeWorker = Worker;
    window.Worker = class extends NativeWorker {
      postMessage(data) { data.url = '/__fixture/synthetic.pack'; super.postMessage(data); }
    };
  });
  await expect(page.locator('#load-pack')).toBeEnabled();
  await page.locator('#load-pack').click();
  await expect.poll(() => page.evaluate(() => ({pack:document.querySelector('#pack-status').textContent, status:document.querySelector('#status').textContent}))).toEqual({pack:'Pack disponible', status:''});
  await expect(page.locator('#play')).toBeEnabled();
  await page.reload();
  await expect(page.locator('#pack-status')).toHaveText('Pack disponible');
  await page.route('**/__fixture/us.pack.sha256', r => r.fulfill({body:'a'.repeat(64)}));
  await page.reload();
  await expect(page.locator('#pack-status')).toHaveText('Pack desactualizado');
  await expect(page.locator('#play')).toBeDisabled();
  await page.route('**/__fixture/us.pack.sha256', r => r.fulfill({body:sha}));
  await page.reload();
  await expect(page.locator('#play')).toBeEnabled();
  await page.route('**/?pack=1&frames=1000000000', r => r.fulfill({body:'game navigation'}));
  await page.locator('#play').click();
  await expect(page).toHaveURL(/\/\?pack=1&frames=1000000000$/);
  expect(failures).toEqual([]);
});
test('failed replacement invalidates the existing sidecar', async ({page}) => {
  await page.route('**/__fixture/us.pack.sha256', r => r.fulfill({body:sha}));
  await page.goto('/');
  await page.evaluate(() => {
    window.fixtureURL = '/__fixture/synthetic.pack';
    const NativeWorker = Worker;
    window.Worker = class extends NativeWorker {
      postMessage(data) { data.url = window.fixtureURL; super.postMessage(data); }
    };
  });
  await expect(page.locator('#load-pack')).toBeEnabled();
  await page.locator('#load-pack').click();
  await expect(page.locator('#pack-status')).toHaveText('Pack disponible');
  await page.evaluate(() => { window.fixtureURL = '/__fixture/missing.pack'; });
  await page.locator('#load-pack').click();
  await expect(page.locator('#status')).toContainText('fixture HTTP 404');
  await expect(page.locator('#play')).toBeDisabled();
  await page.reload();
  await expect(page.locator('#pack-status')).toHaveText('Pack ausente');
});
