#!/usr/bin/env python3
"""Writes _bmad/custom/<skill>.toml so the bmad-build implementation handoff and every default
BMAD review layer run on Claude Sonnet subagents (Agent tool, model "sonnet") with their original
prompts, keeping the orchestrating session's tokens for orchestration and triage. Replaces the
Codex routing (tools/port/codex-run.sh) since the Codex license ended on 2026-11-12. Re-run after
updating BMAD so the prompts follow upstream."""
import pathlib
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SKILLS = ["bmad-build", "bmad-code-review"]
SPAWN = ("Launch a context-free subagent with the Agent tool, subagent_type `general-purpose`, "
         "model `sonnet`, launched in the same turn as the other layers")
READ_ONLY = ("You are a reviewer: do not edit, write or delete files, and do not commit. "
             "Ignore the session steps in CLAUDE.md (STATUS.md, sprint, commit and push).")
# The implementer runs on the host like the orchestrator and builds through the port image.
HANDOFF = """Launch a subagent with no prior conversation context with the Agent tool, subagent_type `general-purpose`, model `sonnet`. It runs in the background: arm a Monitor on `{project-root}/tools/port/agent-watch.sh` right after launching it (CLAUDE.md, "Operación de cada sesión", item 6) and wait for its completion notification. Its final message is the implementer's report. If it fails, report the error to the user and implement directly from the spec. Prompt:

> Read {spec_file} fully and implement it — the spec is the sole source of truth. Load every file listed in its frontmatter `context:` before you start.
>
> Build and test inside the port image, never on the host toolchain: single commands and single-threaded captures with `tools/port/docker_run.sh`, parallel work (full `ctest -j`, several scenes, web and native builds together) with `tools/port/remote_run.sh` (`docs/port/setup.md`). Web (Playwright) suites need PulseAudio: run them locally with `DW_IMAGE=dw-port:remote tools/port/docker_run.sh`, keep clock-sensitive suites serial, and take final class B evidence with `tools/port/remote_run.sh`; both with `DW1_DISC_DIR=/dw/game_rom/extracted`. Ignore the session steps in CLAUDE.md (STATUS.md, sprint, commit and push): do not commit or push, and do not spawn subagents.
>
> When done, report what you changed, how you verified it, and anything left incomplete or risky.
"""
# These layers run in one subagent so the diff and code are read once instead of three times.
# Order keeps the isolation that matters: blind-hunter finishes before any claims are read, and
# edge-case-hunter, the only layer that reads the claims file, goes last. The reviews get the diff
# without docs/implementation-artifacts: the spec there would unblind blind-hunter, and the
# evidence logs are test output, not code.
MERGED = ["blind-hunter", "verification-gap", "edge-case-hunter"]
MERGED_WRAPPER = """First run this with the Bash tool:

awk '/^diff --git /{skip = $4 ~ "^b/docs/implementation-artifacts/"} !skip' {diff_file} > {diff_file}.code

Then %s, with the prompt below. Its final message has one section per review headed `## <layer id>`; treat each section as the findings of the layer with that id, verbatim. A failed subagent means all %d layers failed; a missing or empty section means that layer failed.

Prompt:

You will run %d independent reviews of the same change, in the order given. Finish each review before reading anything the next one points to, and do not let a later review's inputs change an earlier review's findings. Your final message has exactly one section per review, headed `## <id>`, containing that review's output. %s

%s
"""


def body(layer):
    return layer["instruction"].strip().partition("\n")[2].strip()


def entry(table, lid, name, instruction, when=None):
    assert "'''" not in instruction
    out = [f"[[workflow.{table}]]", f'id = "{lid}"', f'name = "{name}"']
    if when:
        out.append(f"when = '{when}'")
    out.append(f"instruction = '''\n{instruction}'''\n")
    return "\n".join(out)


def merged(table, layers):
    reviews = [f"### Review {i}: id `{l['id']}`\n\n{body(l)}" for i, l in enumerate(layers, 1)]
    instruction = MERGED_WRAPPER % (SPAWN[0].lower() + SPAWN[1:], len(layers), len(layers), READ_ONLY,
                                    "\n\n".join(reviews).replace("{diff_file}", "{diff_file}.code"))
    return entry(table, "sonnet-merged", " + ".join(l["name"] for l in layers) + " (Sonnet)", instruction)


def layer(table, l):
    instruction = f"{SPAWN}, with this prompt:\n\n{body(l)}\n\n{READ_ONLY}\n"
    return entry(table, l["id"], f"{l['name']} (Sonnet)", instruction, l.get("when"))


for skill in SKILLS:
    workflow = tomllib.loads((ROOT / f".claude/skills/{skill}/customize.toml").read_text())["workflow"]
    parts = ["# Generated by tools/port/bmad_layers.py: work runs on Sonnet subagents. Do not edit.\n"]
    if "implementation_handoff" in workflow:
        parts.append(f"[workflow]\nimplementation_handoff = '''\n{HANDOFF}'''\n")
    for table in ("review_layers", "oneshot_review_layers"):
        layers = workflow.get(table, [])
        group = sorted((l for l in layers if l["id"] in MERGED and not l.get("when")),
                       key=lambda l: MERGED.index(l["id"]))
        if len(group) > 1:
            parts.append(merged(table, group))
            # Layers merge with the defaults by id; an empty instruction disables a default.
            parts += [f"[[workflow.{table}]]\nid = \"{l['id']}\"\ninstruction = ''\n" for l in group]
        else:
            group = []
        parts += [layer(table, l) for l in layers if l not in group]
    (ROOT / f"_bmad/custom/{skill}.toml").write_text("\n".join(parts))
