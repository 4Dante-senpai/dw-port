#!/usr/bin/env python3
"""Writes _bmad/custom/<skill>.toml so every default BMAD review layer runs on Codex
(tools/port/codex-run.sh) with its original prompt instead of a Claude subagent.
Re-run after updating BMAD so the prompts follow upstream."""
import pathlib
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SKILLS = ["bmad-build", "bmad-code-review"]
WRAPPER = """Run this with the Bash tool (foreground, timeout 600000 ms), launched in the same turn as the other layers. Its stdout is this layer's findings, verbatim; a nonzero exit or empty output means the layer failed.

{project-root}/tools/port/codex-run.sh read-only <<'CODEX_PROMPT'
%s
CODEX_PROMPT
"""


def layer(table, layer):
    _, _, prompt = layer["instruction"].partition("\n")
    out = [f"[[workflow.{table}]]", f'id = "{layer["id"]}"', f'name = "{layer["name"]} (Codex)"']
    if layer.get("when"):
        out.append(f"when = '{layer['when']}'")
    instruction = WRAPPER % prompt.strip()
    assert "'''" not in instruction
    out.append(f"instruction = '''\n{instruction}'''\n")
    return "\n".join(out)


for skill in SKILLS:
    workflow = tomllib.loads((ROOT / f".claude/skills/{skill}/customize.toml").read_text())["workflow"]
    parts = ["# Generated by tools/port/codex_bmad_layers.py: review layers run on Codex. Do not edit.\n"]
    for table in ("review_layers", "oneshot_review_layers"):
        parts += [layer(table, l) for l in workflow.get(table, [])]
    (ROOT / f"_bmad/custom/{skill}.toml").write_text("\n".join(parts))
