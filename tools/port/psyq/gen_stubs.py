#!/usr/bin/env python3
"""Generate a stub for every PsyQ function the game calls that the port does not implement yet.

Inputs: the PsyQ function list (psyq_functions.tsv), the game objects and the port's PsyQ,
runtime and Backend libraries. A stub logs its first call (port_stub_hit) and returns 0, or the
value listed in stub_returns.tsv when 0 would make the game wait forever (each row says why).
PsyQ's libc is left
to the host C library unless defined by the port (setjmp/longjmp are mapped by port_game.h).
Unimplemented port GTE calls (port_gte_*) are counted separately; the Backend supplies the
GTE model. Prints the coverage counters.
Usage: gen_stubs.py NM FUNCTIONS_TSV OUT_C PORT_LIBS GAME_OBJ...   (PORT_LIBS: ';'-separated)

ponytail: stubs are unprototyped `long f()`, fine for i686 cdecl; the web build needs typed
stubs (wasm checks signatures), see story 4.1.
"""
import pathlib
import subprocess
import sys


NM = "nm"


def rows(path):
    return [line.split("\t") for line in pathlib.Path(path).read_text().splitlines()[1:]
            if line.strip()]


def nm(paths, *flags):
    out = subprocess.run([NM, *flags, *map(str, paths)], capture_output=True, text=True,
                         check=True).stdout
    return {line.split()[-1] for line in out.splitlines() if line and not line.endswith(":")}


def classify(undefined, defined_by_port, lib_of):
    """PsyQ symbols the game uses, split into port-implemented, host libc and stubs."""
    used = sorted(s for s in undefined if s in lib_of)
    implemented = [s for s in used if s in defined_by_port]
    host_libc = [s for s in used if lib_of[s] == "libc" and s not in defined_by_port]
    stubs = sorted(s for s in undefined
                   if (s in lib_of and lib_of[s] != "libc" or s.startswith("port_gte_"))
                   and s not in defined_by_port)
    return used, implemented, host_libc, stubs


def main():
    global NM
    NM, tsv, out = sys.argv[1], sys.argv[2], pathlib.Path(sys.argv[3])
    port_libs, objs = sys.argv[4].split(";"), sys.argv[5:]
    lib_of = {r[0]: r[1] for r in rows(tsv)}
    returns = {r[0]: r[1] for r in rows(pathlib.Path(tsv).with_name("stub_returns.tsv"))}
    unknown = sorted(set(returns) - set(lib_of))
    if unknown:
        sys.exit(f"gen_stubs: stub_returns.tsv names unknown functions: {unknown}")
    undefined = nm(objs, "-u") - nm(objs, "--defined-only", "--extern-only")
    defined_by_port = nm(port_libs, "--defined-only", "--extern-only")
    used, implemented, host_libc, stubs = classify(undefined, defined_by_port, lib_of)
    if any(s.startswith("port_gte_") for s in stubs):
        sys.exit("gen_stubs: the Backend must define every port_gte_* call (no GTE stubs)")
    lines = ["/* Generated by tools/port/psyq/gen_stubs.py. Do not edit. */",
             "void port_stub_hit(const char *name, int *seen);", ""]
    for s in stubs:
        lines += [f"long {s}() {{ static int seen; port_stub_hit(\"{s}\", &seen); "
                  f"return {returns.get(s, '0')}; }}"]
    text = "\n".join(lines) + "\n"
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    print(f"psyq: used={len(used)} implemented={len(implemented)} host_libc={len(host_libc)} "
          f"stubs={len([s for s in stubs if s in lib_of])} gte_stubs="
          f"{len([s for s in stubs if s.startswith('port_gte_')])}")


if __name__ == "__main__":
    main()
