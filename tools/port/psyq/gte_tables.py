#!/usr/bin/env python3
"""Generate EXE offsets/sizes of the read-only libgte tables from the USA config."""
import pathlib
import re
import sys

import yaml

TABLES = ("rsin_tbl", "SQRT", "rcossin_tbl", "ratan_tbl")


def values(config):
    segments = yaml.safe_load((config / "main.yaml").read_text())["segments"]
    main = next(s for s in segments if isinstance(s, dict) and s.get("name") == "main")
    symbols = dict((name, int(addr, 16)) for name, addr in re.findall(
        r"^\s*(\w+)\s*=\s*(0x[0-9a-fA-F]+)\s*;", (config / "symbols.txt").read_text(), re.M))
    addresses = sorted(set(symbols.values()))
    result = {}
    for name in TABLES:
        addr = symbols[name]
        following = next(a for a in addresses if a > addr)
        offset = addr - main["vram"] + main["start"]
        if offset < main["start"] or (following - addr) % 2:
            raise ValueError(f"invalid table region: {name}")
        result[name] = offset, following - addr
    return result


def generate(config, out):
    regions = values(config)
    text = "/* Generated by tools/port/psyq/gte_tables.py. Do not edit. */\n"
    for name, (offset, size) in regions.items():
        text += f"#define DW1_GTE_{name.upper()}_OFFSET 0x{offset:X}u\n"
        text += f"#define DW1_GTE_{name.upper()}_SIZE 0x{size:X}u\n"
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)


if __name__ == "__main__":
    generate(pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]))
