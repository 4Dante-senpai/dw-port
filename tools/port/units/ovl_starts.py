#!/usr/bin/env python3
"""Generate the overlay load addresses (<ovl>_START) from the PS1 overlay linker script.

config/<version>/overlay.ld groups overlays as `OVERLAY 0x80052AE0 : NOCROSSREFS { .BTL {
btl_START = .; ...`; every <ovl>_START is the address of its OVERLAY statement. Writes a header
that defines each one as a pointer into the port's arena (PS1_RAM_ADDR, port_game.h). Each
define is guarded, so a <ovl>_START the game defines by hand (shop_START in USA) wins.
Usage: ovl_starts.py LDSCRIPT OUT
"""
import pathlib
import re
import sys


def starts(text):
    """Returns ({name: address}, [errors])."""
    base, out, errors = None, {}, []
    for line in text.splitlines():
        if re.match(r"\s*OVERLAY\b", line):
            m = re.match(r"\s*OVERLAY\s+(0x[0-9A-Fa-f]+)\s*:", line)
            if not m:
                errors.append(f"unparsed OVERLAY statement: {line.strip()}")
                base = None
                continue
            base = int(m.group(1), 16)
            if not 0x80000000 <= base < 0x80200000:
                errors.append(f"OVERLAY {base:#x} is not in PS1 RAM")
            continue
        m = re.match(r"\s*(\w+)_START\s*=\s*\.\s*;", line)
        if m:
            name = m.group(1)
            if base is None:
                errors.append(f"{name}_START outside a parsed OVERLAY statement")
            elif name in out:
                errors.append(f"duplicate {name}_START")
            else:
                out[name] = base
    return out, errors


def render(found):
    lines = ["/* Generated by tools/port/units/ovl_starts.py from overlay.ld. Do not edit. */",
             "#ifndef DW1_OVERLAY_STARTS_H", "#define DW1_OVERLAY_STARTS_H", ""]
    for name, addr in sorted(found.items()):
        lines += [f"#ifndef {name}_START",
                  f"#define {name}_START ((char *)PS1_RAM_ADDR(0x{addr:08X}u))", "#endif"]
    return "\n".join(lines + ["", "#endif", ""])


if __name__ == "__main__":
    found, errors = starts(pathlib.Path(sys.argv[1]).read_text())
    if errors or not found:
        sys.exit("ovl_starts: " + "\n".join(errors or ["no <ovl>_START found"]))
    out = pathlib.Path(sys.argv[2])
    text = render(found)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
