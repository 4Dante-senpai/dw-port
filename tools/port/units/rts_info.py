#!/usr/bin/env python3
"""Generate the PS1 values of the CodeWarrior linker words the game reads (__rts_info_t__.h):
_stack_addr and _stack_size from config/<v>/main.ld (`_stack_addr = .; LONG(0x801FFF00)`), and
_end = main_BSS_END, the end of the main .bss segment (config/<v>/bss.yaml `end:`).
Usage: rts_info.py CONFIG_DIR OUT_H
"""
import pathlib
import re
import sys

import yaml


def values(config):
    ld = (config / "main.ld").read_text()
    out = {}
    for name in ("_stack_addr", "_stack_size"):
        m = re.search(rf"{name}\s*=\s*\.\s*;\s*LONG\((0x[0-9A-Fa-f]+)\)", ld)
        if not m:
            sys.exit(f"rts_info: {name} not found in main.ld")
        out[name] = int(m.group(1), 16)
    if not re.search(r"_end\s*=\s*\.\s*;\s*LONG\(main_BSS_END\)", ld):
        sys.exit("rts_info: _end is not LONG(main_BSS_END) in main.ld")
    out["_end"] = yaml.safe_load((config / "bss.yaml").read_text())["end"]
    return out


if __name__ == "__main__":
    v = values(pathlib.Path(sys.argv[1]))
    text = "/* Generated by tools/port/units/rts_info.py. Do not edit. */\n" + "".join(
        f"#define DW1_RTS{name.upper()} 0x{value:08X}u\n" for name, value in v.items())
    out = pathlib.Path(sys.argv[2])
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
